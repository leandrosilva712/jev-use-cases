"""Rebuild the old version's tuning, predictions and report with the current method.

Uses Jev's cached answers to the old wording (old_version/results/jev/raw.json)
and the same code as the current version: the room checks tuned on dev
(jev.tune.TUNED_ARGUMENTS), the other checks at 0.5, and the four-scenario
report. No API calls; the LLM results are the shared results/llm/test.jsonl.

Run (from smart_home/):  python -m old_version.regenerate
"""

from __future__ import annotations

import json

import pandas as pd

from common.paths import COMMANDS_CSV, ROOT
from evaluation.evaluate import score, write_mistakes
from evaluation.report import build_report
from jev.assistant import predictions
from jev.tune import cutoff_config, save_tuning, tune_cutoffs

OLD = ROOT / "old_version"
RAW_PATH = OLD / "results" / "jev" / "raw.json"


def main() -> None:
    raw = json.loads(RAW_PATH.read_text())
    commands = pd.read_csv(COMMANDS_CSV)
    dev = commands[commands["split"] == "dev"]

    cutoffs, sweeps = tune_cutoffs(dev, raw)
    save_tuning(dev, raw, cutoffs, sweeps, OLD / "jev" / "config.json", OLD / "results" / "jev" / "dev_mistakes.csv")

    for split in ("dev", "test"):
        rows = commands[commands["split"] == split]
        records = predictions(rows, raw, cutoff_config(cutoffs))
        out = OLD / "results" / "jev" / f"{split}.jsonl"
        out.write_text("".join(json.dumps(r) + "\n" for r in records))
        if split == "test":
            write_mistakes(score(rows, records), out.with_name("test_mistakes.csv"))

    build_report(raw, OLD / "results" / "report",
                 "Old wording (old_version/jev/spec.json). Generated by `python -m old_version.regenerate` "
                 f"from cached answers: Jev {RAW_PATH.relative_to(ROOT)}.")


if __name__ == "__main__":
    main()
